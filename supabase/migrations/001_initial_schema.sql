create extension if not exists pgcrypto;

create type public.record_status as enum ('active','inactive','voided');
create type public.visit_status as enum ('active','completed','cancelled');
create type public.sale_status as enum ('draft','completed','voided','partially_refunded','refunded');
create type public.payment_method as enum ('cash','instapay','wallet');
create type public.payment_status as enum ('pending','confirmed','failed','refunded');
create type public.sync_status as enum ('pending','processing','synced','failed');
create type public.stock_movement_type as enum ('purchase','sale','recipe_consumption','waste','adjustment_in','adjustment_out','return_in','return_out');

create table public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null,
  phone text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.roles (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  name text not null,
  is_system_role boolean not null default false,
  created_at timestamptz not null default now()
);
create table public.permissions (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  description text not null
);
create table public.role_permissions (
  role_id uuid not null references public.roles(id) on delete cascade,
  permission_id uuid not null references public.permissions(id) on delete cascade,
  primary key(role_id, permission_id)
);
create table public.user_roles (
  user_id uuid not null references auth.users(id) on delete cascade,
  role_id uuid not null references public.roles(id) on delete restrict,
  assigned_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  primary key(user_id, role_id)
);

create table public.devices (
  id uuid primary key default gen_random_uuid(),
  device_code text not null unique,
  display_name text not null,
  is_active boolean not null default true,
  last_seen_at timestamptz,
  created_at timestamptz not null default now()
);

create table public.guardians (
  id uuid primary key default gen_random_uuid(),
  full_name text not null,
  phone text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index guardians_phone_idx on public.guardians(phone);

create table public.children (
  id uuid primary key default gen_random_uuid(),
  full_name text not null,
  date_of_birth date,
  notes text,
  status public.record_status not null default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.visits (
  id uuid primary key default gen_random_uuid(),
  visit_number bigint generated by default as identity unique,
  guardian_id uuid references public.guardians(id) on delete set null,
  guardian_name_snapshot text not null,
  guardian_relation text not null,
  guardian_phone_snapshot text not null,
  child_count integer not null check (child_count > 0),
  checked_in_at timestamptz not null,
  checked_out_at timestamptz,
  status public.visit_status not null default 'active',
  pricing_type text not null check (pricing_type in ('fixed','hourly','offer','membership')),
  price_rule_id uuid,
  offer_id uuid,
  membership_id uuid,
  amount_before_discount numeric(12,2) not null default 0 check (amount_before_discount >= 0),
  discount_amount numeric(12,2) not null default 0 check (discount_amount >= 0),
  final_amount numeric(12,2) not null default 0 check (final_amount >= 0),
  cashier_user_id uuid references auth.users(id) on delete set null,
  device_id uuid references public.devices(id) on delete set null,
  client_created_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (checked_out_at is null or checked_out_at >= checked_in_at),
  check (discount_amount <= amount_before_discount)
);
create index visits_status_checkin_idx on public.visits(status, checked_in_at desc);
create index visits_phone_idx on public.visits(guardian_phone_snapshot);

create table public.visit_children (
  visit_id uuid not null references public.visits(id) on delete restrict,
  child_id uuid references public.children(id) on delete set null,
  child_name_snapshot text not null,
  created_at timestamptz not null default now(),
  primary key(visit_id, child_name_snapshot)
);

create table public.price_rules (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  pricing_type text not null check (pricing_type in ('fixed','hourly')),
  price numeric(12,2) not null check (price >= 0),
  unit_minutes integer check (unit_minutes is null or unit_minutes > 0),
  is_active boolean not null default true,
  valid_from timestamptz not null default now(),
  valid_until timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  check (valid_until is null or valid_until > valid_from)
);

create table public.offers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  description text,
  offer_type text not null check (offer_type in ('fixed_price','percentage_discount','amount_discount','bundle')),
  value numeric(12,2) not null default 0 check (value >= 0),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  is_active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  check (ends_at > starts_at)
);

create table public.memberships (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  duration_days integer not null default 30 check (duration_days > 0),
  included_visits integer check (included_visits is null or included_visits > 0),
  price numeric(12,2) not null check (price >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
create table public.customer_memberships (
  id uuid primary key default gen_random_uuid(),
  guardian_id uuid references public.guardians(id) on delete restrict,
  membership_id uuid not null references public.memberships(id) on delete restrict,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  visits_remaining integer check (visits_remaining is null or visits_remaining >= 0),
  status public.record_status not null default 'active',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  check (ends_at > starts_at)
);
create table public.membership_transactions (
  id uuid primary key default gen_random_uuid(),
  customer_membership_id uuid not null references public.customer_memberships(id) on delete restrict,
  visit_id uuid references public.visits(id) on delete restrict,
  transaction_type text not null check (transaction_type in ('sale','use','renewal','adjustment','refund')),
  quantity integer not null default 1,
  note text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.sales (
  id uuid primary key default gen_random_uuid(),
  sale_number bigint generated by default as identity unique,
  visit_id uuid references public.visits(id) on delete restrict,
  status public.sale_status not null default 'completed',
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  discount_amount numeric(12,2) not null default 0 check (discount_amount >= 0),
  tax_amount numeric(12,2) not null default 0 check (tax_amount >= 0),
  total_amount numeric(12,2) not null default 0 check (total_amount >= 0),
  notes text,
  cashier_user_id uuid references auth.users(id) on delete set null,
  device_id uuid references public.devices(id) on delete set null,
  client_created_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (discount_amount <= subtotal)
);
create index sales_created_at_idx on public.sales(created_at desc);
create table public.sale_items (
  id uuid primary key default gen_random_uuid(),
  sale_id uuid not null references public.sales(id) on delete restrict,
  item_type text not null check (item_type in ('cafe_product','play_entry','other')),
  inventory_item_id uuid,
  description_snapshot text not null,
  quantity numeric(12,3) not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  discount_amount numeric(12,2) not null default 0 check (discount_amount >= 0),
  line_total numeric(12,2) not null check (line_total >= 0),
  created_at timestamptz not null default now()
