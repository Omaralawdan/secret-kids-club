on conflict do nothing;

-- RLS is enabled for every table. The initial policy set is intentionally conservative: authenticated reads are limited to reference data;
-- business records require an explicit role-aware policy or trusted server-side sync endpoint before production use.
do $$
declare t text;
begin
  foreach t in array array[
    'profiles','roles','permissions','role_permissions','user_roles','devices','guardians','children','visits','visit_children',
    'price_rules','offers','memberships','customer_memberships','membership_transactions','sales','sale_items','payments','refunds',
    'cash_sessions','cash_movements','inventory_items','suppliers','purchase_orders','purchase_order_items','recipes','recipe_ingredients',
    'stock_movements','stock_counts','stock_count_items','sync_operations','audit_logs'
  ] loop
    execute format('alter table public.%I enable row level security', t);
  end loop;
end $$;

-- Self profile: users can read and update only their own profile.
create policy "profile_select_self" on public.profiles for select to authenticated using (user_id = auth.uid());
create policy "profile_update_self" on public.profiles for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

-- Reference catalogue read policies for signed-in users; writes are performed through trusted admin/server paths.
create policy "roles_read_authenticated" on public.roles for select to authenticated using (true);
create policy "permissions_read_authenticated" on public.permissions for select to authenticated using (true);
create policy "role_permissions_read_authenticated" on public.role_permissions for select to authenticated using (true);
create policy "price_rules_read_authenticated" on public.price_rules for select to authenticated using (true);
create policy "offers_read_authenticated" on public.offers for select to authenticated using (true);
create policy "memberships_read_authenticated" on public.memberships for select to authenticated using (true);
create policy "inventory_items_read_authenticated" on public.inventory_items for select to authenticated using (true);

-- NOTE: No direct client policies are created for sales, visits, payments, stock movements, or role assignments.
